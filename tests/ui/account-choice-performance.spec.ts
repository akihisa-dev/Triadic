import { test, expect } from '@playwright/test';
import { selectAccount } from './fixtures';

test('大量行でも候補は操作中の一行だけに表示し、同名科目を識別して選ぶ', async ({ page }) => {
  await page.goto('/tests/ui/performance-preview.html?mode=initiative&count=600&sameNames=1');
  const first = page.getByRole('combobox', { name: '1行目の勘定科目', exact: true });
  await expect(first).toHaveValue('同名科目');
  await expect(page.getByRole('combobox')).toHaveCount(200);
  await expect(page.getByRole('option')).toHaveCount(0);
  await first.click();
  await expect(page.getByRole('option')).toHaveCount(601);
  await first.press('ArrowDown');
  await first.press('Enter');
  await expect(page.getByRole('option')).toHaveCount(0);
  await first.click();
  await expect(page.locator('[role="option"][aria-selected="true"]')).toHaveAttribute('data-account-id', '2');
  await first.press('Escape');
  await selectAccount(first, '600');
  await expect(first).toHaveValue('科目599');
  const cell = page.locator('input[data-row="0"][data-column="0"]');
  await cell.fill('0.001');
  await expect(first).toBeDisabled();
  await cell.press('Escape');
  await expect(cell).toHaveValue('0');
  await expect(first).toBeEnabled();
  const second = page.getByRole('combobox', { name: '2行目の勘定科目', exact: true });
  await selectAccount(second, '1');
  await expect(second).toHaveValue('同名科目');
  await expect(page.getByRole('option')).toHaveCount(0);
});
