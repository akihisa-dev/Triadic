standalone("分類と備考を合わせて検索し、一致した分類だけを表示して最新の改名へ追従する", async ({ page }) => {
  await page.goto("/tests/ui/initiative-search.html");
  const trigger = page.getByRole("button", { name: "施策を検索", exact: true });
  await trigger.click();
  const dialog = page.getByRole("dialog"), input = dialog.getByRole("searchbox", { name: "施策名・備考・分類", exact: true });
  await input.fill("運輸 コスト");
  await expect(dialog.getByLabel("検索結果件数")).toHaveText("1件 / 全125件");
  await expect(dialog.getByRole("listitem")).toContainText("部署：運輸部");
  await expect(dialog.getByRole("listitem").locator("p").last()).toHaveText("展開：コスト　部署：運輸部");
  await input.fill("上期 xyz 運行");
  await expect(dialog.getByRole("listitem").first().locator("p").last()).toHaveText("展開区分：運行効率化　業種：一般貨物ＸＹＺ　期間：上期");
  await input.fill("運輸 共通");
  await expect(dialog).toContainText("条件に一致する施策はありません。");
  await input.fill("運輸");
  await input.press("Enter");
  await expect(page.getByLabel("移動先")).toHaveText("確認施策125");
  await page.getByRole("button", { name: "部署名を更新", exact: true }).click();
  await trigger.click();
  await expect(input).toHaveValue("運輸");
  await expect(dialog).toContainText("条件に一致する施策はありません。");
  await input.fill("配送");
  await expect(dialog.getByRole("listitem")).toContainText("部署：配送部");
  await input.fill("");
  await expect(dialog.getByRole("listitem").first().locator("p")).toHaveCount(1);
  await expect(dialog.getByRole("searchbox")).toHaveCount(1);
});

test("共通検索から備考で施策を探し、詳細へ移動して閉じる操作もできる", async ({ page, app }, info) => {
  await page.goto("/tests/ui/preview.html");
  await app.getByRole("button", { name: "ファイルを開く", exact: true }).click();
  const trigger = app.getByRole("button", { name: "施策を検索", exact: true });
  await trigger.click();
  const dialog = app.getByRole("dialog", { name: "施策を検索", exact: true });
  const input = dialog.getByRole("searchbox", { name: "施策名・備考・分類", exact: true });
  await expect(input).toBeFocused();
  await input.fill("代理店 販売");
  await expect(dialog.getByLabel("検索結果件数")).toHaveText("1件 / 全14件");
  await settleMotion(app.locator("body"));
  await page.screenshot({ path: `/tmp/triadic-search-${info.project.name}.png` });
  await input.press("Escape");
  await expect(dialog).toHaveCount(0);
  await expect(trigger).toBeFocused();
  await trigger.click();
  await input.fill("代理店");
  await dialog.getByRole("button", { name: "既存商品の販売拡大", exact: true }).click();
  await expect(app.getByRole("textbox", { name: "施策名", exact: true })).toHaveValue("既存商品の販売拡大");
  await expect(app.getByRole("spinbutton", { name: "売上高 4月の金額", exact: true }).first()).toHaveValue("120");
  await app.getByRole("button", { name: "前の画面に戻る", exact: true }).click();
  await expect(app.getByRole("heading", { name: "Home", exact: true })).toBeVisible();
  await expect(app.getByRole("button", { name: "操作を取り消す", exact: true })).toBeDisabled();
});

test("新規入力を保持して検索でき、未保存編集では検索を止め、過去は閲覧専用で開く", async ({ page, app }) => {
  await page.goto("/tests/ui/preview.html");
  await app.getByRole("button", { name: "ファイルを開く", exact: true }).click();
  const trigger = app.getByRole("button", { name: "施策を検索", exact: true });
  await trigger.click();
  const dialog = app.getByRole("dialog", { name: "施策を検索", exact: true });
  await dialog.getByRole("searchbox").fill("既存商品の販売拡大");
  await dialog.getByRole("searchbox").press("Enter");
  await app.getByRole("textbox", { name: "施策名", exact: true }).fill("保存待ちの施策名");
  await expect(trigger).toBeDisabled();
  await expect(trigger).toBeEnabled();
  await app.getByRole("button", { name: "複製して新規作成", exact: true }).click();
  await app.getByRole("textbox", { name: "施策名", exact: true }).fill("保持する新規入力");
  await trigger.click();
  await dialog.getByRole("searchbox").fill("季節キャンペーン");
  await dialog.getByRole("searchbox").press("Enter");
  await expect(app.getByRole("textbox", { name: "施策名", exact: true })).toHaveValue("季節キャンペーン");
  await app.getByRole("button", { name: "前の画面に戻る", exact: true }).click();
  await expect(app.getByRole("textbox", { name: "施策名", exact: true })).toHaveValue("保持する新規入力");
  await app.getByRole("button", { name: "サイドバーを開く", exact: true }).click();
  await app.getByRole("navigation", { name: "メインナビゲーション" }).getByRole("button", { name: "履歴", exact: true }).click();
  await app.getByRole("alertdialog", { name: "履歴を開きますか？", exact: true }).getByRole("button", { name: "はい", exact: true }).click();
  await app.locator(".history-date").last().click();
  await trigger.click();
  await dialog.getByRole("searchbox").fill("履歴確認用の過去の状態");
  await dialog.getByRole("button", { name: "既存商品の販売拡大", exact: true }).click();
  await expect(app.getByRole("textbox", { name: "備考", exact: true })).toHaveValue("履歴確認用の過去の状態");
  await expect(app.getByRole("textbox", { name: "施策名", exact: true })).toBeDisabled();
});

standalone("全件検索は50件ずつ表示し、入力・文字列の安全性・日本語変換・空の計画を扱う", async ({ page }) => {
  await page.goto("/tests/ui/initiative-search.html");
  await page.getByRole("button", { name: "施策を検索", exact: true }).click();
  const dialog = page.getByRole("dialog"), input = dialog.getByRole("searchbox");
  await expect(dialog.getByLabel("検索結果件数")).toHaveText("125件 / 全125件");
  await expect(dialog.getByRole("listitem")).toHaveCount(50);
  await dialog.getByRole("button", { name: "次へ", exact: true }).click();
  await expect(dialog.getByRole("button", { name: "確認施策51", exact: true })).toBeVisible();
  await dialog.getByRole("button", { name: "次へ", exact: true }).click();
  await expect(dialog.getByRole("listitem")).toHaveCount(25);
  await input.fill("abc コスト");
  await expect(dialog.getByLabel("検索結果件数")).toHaveText("1件 / 全125件");
  await expect(dialog).toContainText("<img src=x onerror=alert(1)>");
  await expect(dialog.locator("img")).toHaveCount(0);
  await input.dispatchEvent("keydown", { key: "Enter", isComposing: true, keyCode: 229 });
  await expect(dialog).toBeVisible();
  await input.fill("該当なし");
  await input.press("Enter");
  await expect(dialog).toContainText("条件に一致する施策はありません。");
  await input.fill("確認施策1");
  await expect(dialog.getByRole("button", { name: "確認施策1", exact: true })).toBeVisible();
  await input.press("Enter");
  await expect(page.getByLabel("移動先")).toHaveText("確認施策1");
  await page.getByRole("button", { name: "対象を切り替え", exact: true }).click();
  await page.getByRole("button", { name: "施策を検索", exact: true }).click();
  await expect(dialog).toContainText("登録された施策はありません。");
  await dialog.getByRole("button", { name: "閉じる", exact: true }).click();
  await expect(page.getByRole("button", { name: "施策を検索", exact: true })).toBeFocused();
});
