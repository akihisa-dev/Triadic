test("試算の採否・金額・月移動・取消を元予算と分離する", async ({ page, app }) => {
  await page.goto("/tests/ui/preview.html?scenario=save-failure");
  await app.getByRole("button", { name: "ファイルを開く", exact: true }).click();
  const mode = app.getByRole("combobox", { name: "作業モード", exact: true });
  const undo = app.getByRole("button", { name: "操作を取り消す", exact: true });
  await mode.selectOption("trial");
  const adopt = app.getByRole("checkbox", { name: `${scenario.initiativeName}を採用`, exact: true });
  await adopt.uncheck();
  const row = app.getByRole("table", { name: "施策一覧", exact: true }).locator("tbody tr").filter({ has: adopt });
  await expect(row).toHaveClass("trial-excluded");
  const amounts = await row.locator("td").allTextContents();
  expect(amounts.slice(3)).toEqual(Array(36).fill("0"));
  await undo.click(); await expect(adopt).toBeChecked();
  await app.getByRole("button", { name: "操作をやり直す", exact: true }).click(); await expect(adopt).not.toBeChecked();
  await app.getByRole("button", { name: scenario.initiativeName, exact: true }).click();
  const june = app.getByRole("spinbutton", { name: "売上高 6月の金額", exact: true });
  await june.fill(scenario.trialAmount);
  const shift = app.getByRole("button", { name: "実施月をまとめて移動", exact: true });
  await expect(shift).toBeEnabled();
  await shift.click();
  await app.getByRole("dialog").getByRole("combobox", { name: "移動月数", exact: true }).selectOption(String(scenario.shiftMonths));
  await app.getByRole("dialog").getByRole("button", { name: "全科目行に移動を反映", exact: true }).click();
  const august = app.getByRole("spinbutton", { name: "売上高 8月の金額", exact: true });
  await expect(august).toHaveValue(scenario.trialAmount);
  await expect(undo).toBeEnabled(); await undo.click(); await expect(june).toHaveValue(scenario.trialAmount);
  await app.getByRole("button", { name: "操作をやり直す", exact: true }).click(); await expect(august).toHaveValue(scenario.trialAmount);
  await app.getByRole("checkbox", { name: "採用", exact: true }).check();
  for (const label of ["前年入力", "入出力", "マスタ", "履歴", "別名で保存", "ファイルを閉じる"]) await expect(app.getByRole("button", { name: label, exact: true })).toBeDisabled();
  await expect(app.getByRole("button", { name: "複製して新規作成", exact: true })).toHaveCount(0);
  await mode.selectOption("budget");
  await app.getByRole("button", { name: "キャンセル", exact: true }).click();
  await expect(mode).toHaveValue("trial"); await expect(august).toHaveValue(scenario.trialAmount);
  await mode.selectOption("budget"); await app.getByRole("button", { name: "予算に戻る", exact: true }).click();
  await expect(mode).toHaveValue("budget"); await expect(undo).toBeDisabled();
  await app.getByRole("button", { name: "施策を検索", exact: true }).click();
  await app.getByRole("dialog").getByRole("searchbox").fill(scenario.initiativeName);
  await app.getByRole("dialog").getByRole("searchbox").press("Enter");
  await expect(june).toHaveValue(scenario.originalAmount);
  await mode.selectOption("trial"); await expect(app.getByRole("checkbox", { name: "採用", exact: true })).toBeChecked();
  await expect(june).toHaveValue(scenario.originalAmount);
  await expect(app.getByRole("alert")).toHaveCount(0);
  await settleMotion(app.locator("body"));
});

test("元予算の保存済み操作と入力中の値を保護する", async ({ page, app }) => {
  await page.goto("/tests/ui/preview.html");
  await app.getByRole("button", { name: "ファイルを開く", exact: true }).click();
  await app.getByRole("button", { name: "施策を検索", exact: true }).click();
  await app.getByRole("dialog").getByRole("searchbox").fill(scenario.initiativeName);
  await app.getByRole("dialog").getByRole("searchbox").press("Enter");
  const mode = app.getByRole("combobox", { name: "作業モード", exact: true });
  const june = app.getByRole("spinbutton", { name: "売上高 6月の金額", exact: true });
  const undo = app.getByRole("button", { name: "操作を取り消す", exact: true });
  await june.fill("60"); await expect(mode).toBeDisabled(); await expect(mode).toBeEnabled();
  await mode.selectOption("trial"); await expect(undo).toBeDisabled();
  await june.fill("0.0001");
  await expect(app.getByRole("alert").filter({ hasText: "入力を反映できませんでした" })).toBeVisible();
  await expect(mode).toBeDisabled();
  await app.getByRole("button", { name: "入力を取り消す", exact: true }).click();
  await expect(june).toHaveValue("60");
  await june.fill("70"); await expect(mode).toBeEnabled();
  await mode.selectOption("budget"); await app.getByRole("button", { name: "予算に戻る", exact: true }).click();
  await expect(june).toHaveValue("60"); await expect(undo).toBeEnabled();
  await undo.click(); await expect(june).toHaveValue("50");
  await app.getByRole("button", { name: "操作をやり直す", exact: true }).click(); await expect(june).toHaveValue("60");
});
