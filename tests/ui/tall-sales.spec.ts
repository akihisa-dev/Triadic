import { test, expect, selectClassification, settleMotion } from './fixtures';
test('売上集計を後方に置いても全行を表示し、前年の後続セルを編集・保存できる',async({page,app})=>{
  await page.goto('/tests/ui/preview.html?data=tall-sales');
  await app.getByRole('button',{name:'ファイルを開く',exact:true}).click();
  const nav=app.getByRole('navigation',{name:'メインナビゲーション'});
  await nav.getByRole('button',{name:'総原価表',exact:true}).click();
  await expect(app.locator('.cost-table.cost-header-scroll')).toHaveCount(1);
  const cost=app.getByRole('region',{name:'総原価表の月別前年・種別別金額',exact:true});
  await cost.evaluate(node=>{node.scrollTop=node.scrollHeight});
  await expect(cost.getByRole('rowheader',{name:'利益率',exact:true})).toBeInViewport();
  await expect.poll(()=>cost.getByRole('rowheader',{name:'利益率',exact:true}).evaluate(node=>{
    const b=node.getBoundingClientRect();return node.contains(document.elementFromPoint(b.x+b.width/2,b.y+b.height/2));
  })).toBe(true);
  await nav.getByRole('button',{name:'前年入力',exact:true}).click();
  await selectClassification(app.getByRole('combobox',{name:'部署名',exact:true}),'部署A');
  await selectClassification(app.getByRole('combobox',{name:'業種名',exact:true}),'直営自動車');
  await page.mouse.move(page.viewportSize()!.width-5,200);
  await settleMotion(app.locator('.home-layout'));
  await expect(app.locator('.previous-grid.cost-header-scroll')).toHaveCount(1);
  const cell=app.getByRole('textbox',{name:'貸倒引当金繰入額 4月の前年金額',exact:true});
  await cell.click();await expect(cell).toBeFocused();
  await expect.poll(()=>cell.evaluate(node=>{const b=node.getBoundingClientRect();return node===document.elementFromPoint(b.x+b.width/2,b.y+b.height/2)})).toBe(true);
  await cell.fill('12.345');await cell.press('Enter');
  await expect(nav.getByRole('button',{name:'総原価表',exact:true})).toBeEnabled();
  await nav.getByRole('button',{name:'総原価表',exact:true}).click();
  await nav.getByRole('button',{name:'前年入力',exact:true}).click();
  await selectClassification(app.getByRole('combobox',{name:'部署名',exact:true}),'部署A');
  await selectClassification(app.getByRole('combobox',{name:'業種名',exact:true}),'直営自動車');
  await page.mouse.move(page.viewportSize()!.width-5,200);
  await settleMotion(app.locator('.home-layout'));
  await expect(cell).toHaveValue('12.345');
  const width=page.viewportSize()!.width;
  await page.setViewportSize({width,height:4000});
  await expect(app.locator('.previous-grid.cost-header-scroll')).toHaveCount(0);
  await page.setViewportSize({width,height:864});
  await expect(app.locator('.previous-grid.cost-header-scroll')).toHaveCount(1);
  await cell.press('Tab');
  const next=app.getByRole('textbox',{name:'貸倒引当金繰入額 5月の前年金額',exact:true});
  await expect(next).toBeFocused();
  await expect.poll(()=>next.evaluate(node=>{const b=node.getBoundingClientRect();return node===document.elementFromPoint(b.x+b.width/2,b.y+b.height/2)})).toBe(true);
});
