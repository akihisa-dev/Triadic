import { test, expect, openInitiativeEntry, selectAccount } from "./fixtures";
import type { FrameLocator } from "@playwright/test";

const account = (app: FrameLocator, row: number) => app.getByRole("combobox", { name: `${row}行目の勘定科目`, exact: true });
const remove = (app: FrameLocator, row: number) => app.getByRole("button", { name: `${row}行目を削除`, exact: true });
const confirm = (app: FrameLocator) => app.getByRole("alertdialog").getByRole("button", { name: "削除", exact: true });
const back = (app: FrameLocator) => app.getByRole("button", { name: "← 施策一覧へ戻る", exact: true });
const cell = (app: FrameLocator, row: number, column: number) => app.locator(`input[data-row="${row}"][data-column="${column}"]`);

test("削除はアイコンで確認し、キャンセル・Escでは両予算の入力を保持する", async ({ page, app }) => {
  await page.goto("/tests/ui/preview.html?data=defaults");
  await expect(page.getByRole("status")).toHaveText("操作できます");
  await app.getByRole("button", { name: "ファイルを開く", exact: true }).click();
  await openInitiativeEntry(app);
  await selectAccount(account(app, 1), { label: "売上高" });
  await cell(app, 0, 0).fill("123.456");
  await app.getByRole("tab", { name: "確定予算", exact: true }).click();
  await cell(app, 0, 0).fill("0");
  await cell(app, 0, 1).fill("150.001");
  await expect(remove(app, 1).locator("svg")).toHaveCount(1);
  await expect(remove(app, 1)).toHaveText("");
  await remove(app, 1).click();
  const dialog = app.getByRole("alertdialog", { name: "勘定科目行を削除", exact: true });
  await expect(dialog).toContainText("1行目「売上高」");
  await expect(dialog).toContainText("一次予算・確定予算の金額も削除されます。");
  await expect(dialog.getByRole("button", { name: "キャンセル", exact: true })).toBeFocused();
  await dialog.getByRole("button", { name: "キャンセル", exact: true }).click();
  await expect(remove(app, 1)).toBeFocused();
  await expect(cell(app, 0, 0)).toHaveValue("0");
  await expect(cell(app, 0, 1)).toHaveValue("150.001");
  await remove(app, 1).click();
  await dialog.press("Escape");
  await app.getByRole("tab", { name: "一次予算", exact: true }).click();
  await expect(cell(app, 0, 0)).toHaveValue("123.456");
  await remove(app, 1).click(); await confirm(app).click();
  await expect(account(app, 1)).toHaveCount(0);
  await app.getByRole("tab", { name: "確定予算", exact: true }).click();
  await expect(cell(app, 0, 0)).toHaveCount(0);
  await expect(app.locator("tfoot td").first()).toHaveText("0");
});

test("ドラッグした行の両予算と手修正を保存し、操作取消・やり直しと上下キーで順序を変更できる", async ({ page, app }) => {
  await page.goto("/tests/ui/preview.html?data=full");
  await expect(page.getByRole("status")).toHaveText("操作できます");
  await app.getByRole("button", { name: "ファイルを開く", exact: true }).click();
  await app.getByRole("navigation", { name: "メインナビゲーション" }).getByRole("button", { name: "施策一覧", exact: true }).click();
  await app.getByRole("button", { name: "科目変更と削除の確認", exact: true }).click();
  await app.getByRole("tab", { name: "一次予算", exact: true }).click();
  await cell(app, 0, 0).fill("100.001");
  await cell(app, 1, 0).fill("200");
  await app.getByRole("tab", { name: "確定予算", exact: true }).click();
  await cell(app, 0, 0).fill("0");
  await cell(app, 0, 1).fill("50");
  await cell(app, 1, 0).fill("300");
  await app.getByRole("heading", { name: "施策入力", exact: true }).click();
  await expect(back(app)).toBeEnabled();
  const source = app.getByRole("button", { name: "1行目を並べ替え", exact: true });
  const target = app.locator(".initiative-amount-table tbody tr").nth(1).locator("th");
  await source.scrollIntoViewIfNeeded();
  const sourceBox = (await source.boundingBox())!;
  await page.mouse.move(sourceBox.x + sourceBox.width / 2, sourceBox.y + sourceBox.height / 2);
  await page.mouse.down();
  // Start the native drag before scrolling a table that can show only one row.
  await page.mouse.move(sourceBox.x + sourceBox.width / 2 + 12, sourceBox.y + sourceBox.height / 2, { steps: 4 });
  await target.scrollIntoViewIfNeeded();
  const targetBox = (await target.boundingBox())!;
  await page.mouse.move(targetBox.x + 15, targetBox.y + targetBox.height - 4, { steps: 5 });
  await page.mouse.up();
  await expect(account(app, 1)).toHaveValue("売上高");
  await expect(cell(app, 0, 0)).toHaveValue("300");
  await expect(cell(app, 1, 0)).toHaveValue("0");
  await expect(cell(app, 1, 1)).toHaveValue("50");
  await expect(back(app)).toBeEnabled();
  await app.getByRole("button", { name: "操作を取り消す", exact: true }).click();
  await expect(account(app, 1)).toHaveValue("未所属費用");
  await app.getByRole("button", { name: "操作をやり直す", exact: true }).click();
  await expect(account(app, 1)).toHaveValue("売上高");
  await expect(back(app)).toBeEnabled(); await back(app).click();
  await app.getByRole("button", { name: "科目変更と削除の確認", exact: true }).click();
  await app.getByRole("tab", { name: "一次予算", exact: true }).click();
  await expect(cell(app, 0, 0)).toHaveValue("200");
  await expect(cell(app, 1, 0)).toHaveValue("100.001");
  await cell(app, 1, 0).fill("110.001");
  await app.getByRole("tab", { name: "確定予算", exact: true }).click();
  await expect(cell(app, 1, 0)).toHaveValue("0");
  await expect(cell(app, 1, 1)).toHaveValue("50");
  await app.getByRole("heading", { name: "施策入力", exact: true }).click();
  await expect(back(app)).toBeEnabled();
  await app.getByRole("button", { name: "2行目を並べ替え", exact: true }).press("ArrowUp");
  await expect(account(app, 1)).toHaveValue("未所属費用");
  await expect(cell(app, 0, 0)).toHaveValue("0");
  await expect(cell(app, 0, 1)).toHaveValue("50");
  await expect(back(app)).toBeEnabled();
  await remove(app, 1).click(); await confirm(app).click();
  await expect(back(app)).toBeEnabled();
  await app.getByRole("button", { name: "操作を取り消す", exact: true }).click();
  await expect(account(app, 1)).toHaveValue("未所属費用");
  await expect(cell(app, 0, 0)).toHaveValue("0");
  await expect(cell(app, 0, 1)).toHaveValue("50");
});

test("削除の保存に失敗したら入力を保ち、入力取消で保存済みの行に戻せる", async ({ page, app }) => {
  await page.goto("/tests/ui/preview.html?data=full&scenario=save-failure");
  await expect(page.getByRole("status")).toHaveText("操作できます");
  await app.getByRole("button", { name: "ファイルを開く", exact: true }).click();
  await app.getByRole("navigation", { name: "メインナビゲーション" }).getByRole("button", { name: "施策一覧", exact: true }).click();
  await app.getByRole("button", { name: "確定予算のゼロ固定", exact: true }).click();
  await remove(app, 1).click(); await confirm(app).click();
  await expect(app.getByRole("alert")).toContainText("自動保存できませんでした");
  await expect(account(app, 1)).toHaveCount(0);
  await app.getByRole("button", { name: "入力を取り消す", exact: true }).click();
  await expect(account(app, 1)).toHaveValue("グループ売上高");
  await app.getByRole("tab", { name: "確定予算", exact: true }).click();
  await expect(cell(app, 0, 0)).toHaveValue("90");
  await expect(cell(app, 0, 6)).toHaveValue("0");
});
