import { test, expect } from './fixtures';

test('明細の値を施策へ反映し、確定の手修正を保ち、月単位で直接入力へ戻せる', async ({ app, page }, info) => {
  await page.goto('/tests/ui/preview.html?data=full');
  await app.getByRole('button', { name: 'ファイルを開く', exact: true }).click();
  await app.getByRole('navigation', { name: 'メインナビゲーション' }).getByRole('button', { name: '明細', exact: true }).click();
  await app.getByRole('button', { name: '全パーツの保存確認を開く', exact: true }).click();
  const output = app.locator('.detail-output-part');
  await output.getByRole('button', { name: '変更', exact: true }).click();
  await output.getByLabel('反映する値', { exact: true }).selectOption({ label: 'パーツ 6：単価差' });
  await output.getByLabel('反映先の科目行', { exact: true }).selectOption({ index: 1 });
  await output.getByLabel('4月', { exact: true }).check();
  await output.getByLabel('5月', { exact: true }).check();
  await output.getByRole('button', { name: '編集を終える', exact: true }).click();
  await output.locator('.detail-initiative-link').click();
  const row = app.getByRole('table', { name: '月別計画金額', exact: true }).locator('tbody tr').first();
  await expect(row.getByRole('spinbutton', { name: '売上高 4月の金額', exact: true })).toHaveValue('0.01');
  await expect(row.getByRole('spinbutton', { name: '売上高 4月の金額', exact: true })).toBeDisabled();
  await app.getByRole('tab', { name: '確定予算', exact: true }).click();
  await expect(row.getByRole('spinbutton', { name: '売上高 4月の金額', exact: true })).toHaveValue('130');
  await expect(row.getByRole('spinbutton', { name: '売上高 5月の金額', exact: true })).toHaveValue('0.01');
  await app.getByRole('tab', { name: '一次予算', exact: true }).click();
  await row.getByRole('button', { name: '売上高 4月の反映元', exact: true }).click();
  await expect(app.getByRole('region', { name: '明細からの反映', exact: true })).toContainText('全パーツの保存確認');
  await page.screenshot({ path: info.outputPath('明細の値と施策の連動.png') });
  await app.getByRole('button', { name: '直接入力へ切り替える', exact: true }).click();
  await expect(row.getByRole('spinbutton', { name: '売上高 4月の金額', exact: true })).toBeEnabled();
  await expect(row.getByRole('spinbutton', { name: '売上高 4月の金額', exact: true })).toHaveValue('0.01');
  await row.getByRole('spinbutton', { name: '売上高 4月の金額', exact: true }).fill('12');
  await row.getByRole('button', { name: '売上高 5月の反映元', exact: true }).click();
  await app.getByRole('button', { name: '反映元の明細を開く', exact: true }).click();
  await app.getByRole('button', { name: 'パーツ 6の入力値を編集', exact: true }).dblclick();
  await app.getByRole('textbox', { name: 'パーツ 6の値', exact: true }).fill('500');
  await app.getByRole('textbox', { name: 'パーツ 6の値', exact: true }).press('Escape');
  await output.locator('.detail-initiative-link').click();
  await expect(row.getByRole('spinbutton', { name: '売上高 4月の金額', exact: true })).toHaveValue('12');
  await expect(row.getByRole('spinbutton', { name: '売上高 5月の金額', exact: true })).toHaveValue('0.5');
  await row.getByRole('button', { name: '売上高 5月の反映元', exact: true }).click();
  await app.getByRole('button', { name: '反映元の明細を開く', exact: true }).click();
  await app.getByRole('button', { name: 'パーツ 6の入力値を編集', exact: true }).dblclick();
  await app.getByRole('textbox', { name: 'パーツ 6の値', exact: true }).fill('');
  await app.getByRole('textbox', { name: 'パーツ 6の値', exact: true }).press('Escape');
  await expect(output).toContainText('数値が未入力です');
  await output.locator('.detail-initiative-link').click();
  await expect(row.getByRole('spinbutton', { name: '売上高 5月の金額', exact: true })).toHaveValue('0.5');
  await expect(row.getByRole('button', { name: '売上高 5月の反映元', exact: true })).toContainText('要確認');
});

test('文章と月別表の切替で値と計算参照が保たれる', async ({ app, page }) => {
  await page.goto('/tests/ui/preview.html?data=full');
  await app.getByRole('button', { name: 'ファイルを開く', exact: true }).click();
  await app.getByRole('navigation', { name: 'メインナビゲーション' }).getByRole('button', { name: '明細', exact: true }).click();
  await app.getByRole('button', { name: '全パーツの保存確認を開く', exact: true }).click();
  await app.getByRole('button', { name: 'パーツ 1のテキストを編集', exact: true }).dblclick();
  await app.getByLabel('文章の種類', { exact: true }).selectOption('heading');
  await app.getByRole('textbox', { name: 'パーツ 1の見出し', exact: true }).press('Escape');
  await expect(app.getByRole('heading', { name: '見積と月別の算定根拠 保存・取消・履歴を確認', exact: true })).toBeVisible();
  const table = app.getByRole('group', { name: 'パーツ 3の横向き12か月', exact: true });
  await table.dblclick();
  await app.getByLabel('月別表の向き', { exact: true }).selectOption('vertical');
  await expect(app.getByRole('textbox', { name: '項目 1の4月', exact: true })).toHaveValue('1');
  await app.getByRole('textbox', { name: '項目 1の4月', exact: true }).fill('7');
  await app.getByLabel('月別表の向き', { exact: true }).selectOption('horizontal');
  await app.getByRole('textbox', { name: '項目 1の4月', exact: true }).press('Escape');
  const calculation = app.locator('.detail-part').nth(7);
  await expect(calculation).toContainText('70 円');
  await expect(calculation).toContainText('120 円');
  const breakdown = app.locator('.detail-part').nth(8);
  await expect(breakdown).toContainText('2500 円');
  await breakdown.getByRole('button', { name: '編集', exact: true }).click();
  await breakdown.getByRole('textbox', { name: '内訳 1の数量', exact: true }).fill('3');
  await expect(breakdown).toContainText('3750 円');
  await calculation.getByRole('button', { name: '編集', exact: true }).click();
  await calculation.getByLabel('計算する値 1', { exact: true }).selectOption({ label: 'パーツ 9：備品の見積 合計' });
  await expect(calculation).toContainText('26250 円');
});
