import assert from 'node:assert/strict';
export function verifySpreadsheetOperation({ SpreadsheetOperation, spreadsheetWorking }) {
  const pending = [], operation = new SpreadsheetOperation(value => pending.push(value));
  const patches = [{ month: 4, before: '0', after: '123.456' }];
  assert.equal(operation.getSnapshot().phase, 'idle');
  const reading = operation.beginReading();
  assert.equal(spreadsheetWorking(operation.getSnapshot()), true);
  assert.equal(operation.beginReading(), null, '同じイベント内の連打を同期的に拒否');
  assert.equal(operation.beginExport('report'), null);
  operation.complete(reading, patches);
  assert.equal(operation.getSnapshot().patches, patches);
  assert.equal(operation.getSnapshot().retry, false);
  assert.equal(pending.at(-1), true, '確認待ちでも移動制限を解除しない');
  assert.equal(spreadsheetWorking(operation.getSnapshot()), false);
  assert.equal(operation.beginExport('previous'), null, '確認待ちを別の出力で置き換えない');
  const saving = operation.beginSaving();
  assert.equal(operation.beginSaving(), null);
  operation.cancelPreview();
  assert.equal(operation.getSnapshot(), saving, '保存中に確認を破棄しない');
  operation.fail(saving);
  assert.equal(operation.getSnapshot().patches, patches);
  assert.equal(operation.getSnapshot().retry, true);
  assert.equal(pending.at(-1), true, '保存失敗でも内容と移動制限を保持');
  operation.complete(operation.beginSaving());
  assert.equal(operation.getSnapshot().phase, 'idle');assert.equal(pending.at(-1), false);
  operation.complete(operation.beginReading(), patches);operation.cancelPreview();
  assert.equal(operation.getSnapshot().phase, 'idle');assert.equal(pending.at(-1), false);
  operation.complete(operation.beginReading(), []);
  assert.equal(operation.getSnapshot().phase, 'idle', '変更なしは確認待ちにしない');
  operation.fail(operation.beginReading());assert.equal(pending.at(-1), false);
  const exporting = operation.beginExport('report');operation.abortExport();
  assert.equal(exporting.controller.signal.aborted, true);
  assert.equal(operation.beginReading(), null, '中止完了まで次の処理を始めない');
  operation.fail(exporting);assert.equal(pending.at(-1), false);
  const next = operation.beginExport('previous');assert.equal(next.controller.signal.aborted, false);
  operation.dispose();assert.equal(next.controller.signal.aborted, true);
  operation.complete(next, patches);assert.equal(operation.getSnapshot().phase, 'idle', '終了後の遅い結果で状態を復活させない');
  assert.equal(pending.at(-1), false);
  console.log('PASS: Excelの同期的二重実行防止、読込・確認・保存失敗・再試行・取消・出力中止・終了後の結果拒否');
}
